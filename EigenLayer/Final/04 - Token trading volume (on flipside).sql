SELECT
    DATE_TRUNC('day', BLOCK_TIMESTAMP) AS day,
    
    sum(CASE WHEN TOKEN_IN = LOWER('0xec53bF9167f50cDEB3Ae105f56099aaaB9061F83') THEN amount_in ELSE 0 END + 
        CASE WHEN TOKEN_OUT = LOWER('0xec53bF9167f50cDEB3Ae105f56099aaaB9061F83') THEN amount_out ELSE 0 END) AS Eigen_TOKEN_VOLUME,
    
    sum(CASE WHEN TOKEN_IN = LOWER('0xec53bF9167f50cDEB3Ae105f56099aaaB9061F83') THEN amount_in_usd ELSE 0 END + 
        CASE WHEN TOKEN_OUT = LOWER('0xec53bF9167f50cDEB3Ae105f56099aaaB9061F83') THEN amount_out_usd ELSE 0 END) AS Eigen_TOKEN_USD_VOLUME,


FROM ethereum.defi.ez_dex_swaps
GROUP BY day
HAVING Eigen_TOKEN_VOLUME > 0
ORDER BY day;
